/**
 * Markdown 渲染容错：把大模型常见的「紧凑写法」规范化成标准 Markdown。
 *
 * 背景
 * ----
 * 中文大模型为了省 token，经常把块级标记后面的空格省掉，例如：
 *   `##Java学习路线`、`-《Java集合与并发编程》`、`1.计算机基础`、`>说明：`
 * 而 CommonMark（markdown-it 的解析规则）规定标题/列表/引用符号后必须有空白字符，
 * 否则**不会**被识别为块级元素 —— 页面就会把 `##`、`-`、`>`、`|` 等符号原样显示出来。
 *
 * 另一个坑：`>说明书...` 这种「伪引用」如果紧跟正文行，会把后续多行都吞进同一个
 * 引用块里（lazy continuation），于是整段文字挤成一坨、显示为纯文本带 `<br>`。
 *
 * 这里在 `md.render()` 之前做一次纯文本规范化，作为**兜底**（提示词层也会同步要求
 * 模型输出规范 Markdown，但模型不一定每次都听话）。本文件刻意不 import 任何依赖，
 * 以便 `node src/utils/markdown.test.mjs` 能通过 data: URL 直接加载被测源码。
 */

/**
 * 规范化紧凑 Markdown，使其符合 CommonMark 的块级解析规则。
 * 幂等：对已经规范的文本再跑一次结果不变。
 *
 * @param {string} text 模型输出的原始 Markdown
 * @returns {string} 规范化后的 Markdown
 */
export const normalizeMarkdown = (text) => {
  if (text === null || text === undefined) return '';
  let s = String(text);

  // 1) 标题：# 与文字之间补空格（##Java -> ## Java）。`##` 后面本来就是空格/行尾时不动。
  s = s.replace(/^([ \t]{0,3}#{1,6})([^\s#])/gm, '$1 $2');

  // 2) 引用：> 与文字之间补空格（>说明 -> > 说明）。
  s = s.replace(/^([ \t]{0,3}>)([^\s>])/gm, '$1 $2');

  // 3) 无序列表：- / * / + 与文字之间补空格。
  //    用负向断言排除分隔线（---）、加粗（**）、以及已经有空格的情况。
  s = s.replace(/^([ \t]*)([-*+])(?![ \t\-*+])(?=\S)/gm, '$1$2 ');

  // 4) 有序列表：1. / 1) 与文字之间补空格（1.计算机 -> 1. 计算机）。
  //    要求标记后紧跟非数字字符，避免把行首的 `3.14` 之类小数误判成列表。
  s = s.replace(/^([ \t]*)(\d{1,3})([.)])(?![ \t)])(?=[^\d\s])/gm, '$1$2$3 ');

  // 5) 表格：行首多写了一个 |（||Java进阶| -> |Java进阶|）。
  s = s.replace(/^([ \t]*)\|\|(?=\S)/gm, '$1|');

  // 6) 引用块结束处补空行：否则紧随其后的正文会被当成引用的延续而被吞掉。
  s = s.replace(/^([ \t]*>[^\n]*)\n(?![ \t]*>)(?=\S)/gm, '$1\n\n');

  // 7) 标题 / 引用 紧跟在正文行之后时，前面补空行，否则不会被解析成块级元素。
  s = s.replace(/([^\n])\n(?=[ \t]*(?:#{1,6}\s|>\s))/g, '$1\n\n');

  // 8) 表格紧跟在非表格行之后时，前面补空行（表格行之间不加，避免把表格拆散）。
  s = s.replace(/([^\n|])\n(?=[ \t]*\|)/g, '$1\n\n');

  return s;
};

export default normalizeMarkdown;
